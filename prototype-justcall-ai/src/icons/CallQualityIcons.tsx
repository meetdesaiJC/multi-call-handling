import type { ReactNode, SVGProps } from "react";

/**
 * The glyphs the Call Quality modal puts beside its tips and help links.
 *
 * Drawn on a **16-unit** grid rather than the library's 24, because that is
 * the grid the Figma set was drawn on and these are only ever rendered at 16 —
 * one tip row, one 16px icon. Re-plotting them at 24 to match
 * `CallControlIcons` would mean redrawing eight glyphs by hand and getting the
 * proportions slightly wrong; the path data here is the design's own.
 *
 * The mic is not here: `IconVoice` from the library is the same drawing, so
 * the tips import it from there (CLAUDE.md §2).
 *
 * Replace these with generated icons once the Figma library carries them.
 */

